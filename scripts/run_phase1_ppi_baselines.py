"""Run Phase 1 PPI baselines on multi-seed split folders.

Inputs are generated by `build_phase1_ppi_multiseed_splits.py`.

Outputs:
- results/phase1/ppi_link_prediction_baselines.csv
- reports/phase1_ppi_link_prediction_baselines.md
- reports/phase1_ppi_link_prediction_baselines.json
"""

from __future__ import annotations

import argparse
import csv
import gzip
import json
import math
import time
from pathlib import Path

import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, brier_score_loss, log_loss, roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler


ROOT = Path(__file__).resolve().parents[1]
SPLIT_ROOT = ROOT / "data" / "processed" / "phase1_ppi_multiseed_splits"
RESULTS_DIR = ROOT / "results" / "phase1"
REPORTS_DIR = ROOT / "reports"

DATASETS = [
    "string_human_physical_v12",
    "biogrid_human_physical",
    "biogrid_human_physical_no_string_overlap",
    "string_human_physical_no_biogrid_overlap",
]
STRATEGIES = ["random", "degree_matched", "two_hop"]
HEURISTICS = ["common_neighbors", "jaccard", "adamic_adar", "preferential_attachment"]


def edge_columns(dataset_id: str) -> tuple[str, str]:
    return ("protein1", "protein2") if dataset_id.startswith("string") else ("entrez_a", "entrez_b")


def open_text(path: Path):
    if path.suffix == ".gz":
        return gzip.open(path, "rt", newline="", encoding="utf-8")
    return path.open(newline="", encoding="utf-8")


def read_edges(path: Path, left_col: str, right_col: str) -> list[tuple[str, str]]:
    with open_text(path) as handle:
        return [tuple(sorted((row[left_col], row[right_col]))) for row in csv.DictReader(handle)]


def build_adjacency(edges: list[tuple[str, str]]) -> dict[str, set[str]]:
    adjacency: dict[str, set[str]] = {}
    for a, b in edges:
        adjacency.setdefault(a, set()).add(b)
        adjacency.setdefault(b, set()).add(a)
    return adjacency


def score_edge(edge: tuple[str, str], adjacency: dict[str, set[str]]) -> dict[str, float]:
    a, b = edge
    neigh_a = adjacency.get(a, set())
    neigh_b = adjacency.get(b, set())
    deg_a = len(neigh_a)
    deg_b = len(neigh_b)
    common = neigh_a & neigh_b
    union = neigh_a | neigh_b
    adamic_adar = 0.0
    for node in common:
        degree = len(adjacency.get(node, set()))
        if degree > 1:
            adamic_adar += 1.0 / math.log(degree)
    return {
        "common_neighbors": float(len(common)),
        "jaccard": float(len(common) / len(union)) if union else 0.0,
        "adamic_adar": adamic_adar,
        "preferential_attachment": float(deg_a * deg_b),
        "degree_u": float(deg_a),
        "degree_v": float(deg_b),
        "abs_degree_diff": float(abs(deg_a - deg_b)),
        "degree_product": float(deg_a * deg_b),
    }


def build_feature_matrix(
    pos_edges: list[tuple[str, str]],
    neg_edges: list[tuple[str, str]],
    adjacency: dict[str, set[str]],
) -> tuple[np.ndarray, np.ndarray, dict[str, np.ndarray]]:
    edges = pos_edges + neg_edges
    labels = np.asarray([1] * len(pos_edges) + [0] * len(neg_edges), dtype=np.int8)
    scored = [score_edge(edge, adjacency) for edge in edges]
    heuristic_scores = {name: np.asarray([row[name] for row in scored], dtype=np.float64) for name in HEURISTICS}
    matrix = np.asarray(
        [
            [
                row["common_neighbors"],
                row["jaccard"],
                row["adamic_adar"],
                row["preferential_attachment"],
                row["degree_u"],
                row["degree_v"],
                row["abs_degree_diff"],
                row["degree_product"],
            ]
            for row in scored
        ],
        dtype=np.float64,
    )
    return matrix, labels, heuristic_scores


def expected_calibration_error(y_true: np.ndarray, y_prob: np.ndarray, n_bins: int = 10) -> float:
    bins = np.linspace(0.0, 1.0, n_bins + 1)
    ece = 0.0
    for left, right in zip(bins[:-1], bins[1:]):
        if right == 1.0:
            mask = (y_prob >= left) & (y_prob <= right)
        else:
            mask = (y_prob >= left) & (y_prob < right)
        if not np.any(mask):
            continue
        ece += float(np.mean(mask)) * abs(float(np.mean(y_prob[mask])) - float(np.mean(y_true[mask])))
    return ece


def make_model(model_name: str, seed: int):
    if model_name == "logistic_regression":
        return make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000, class_weight="balanced", random_state=seed))
    if model_name == "random_forest":
        return RandomForestClassifier(
            n_estimators=200,
            max_depth=16,
            min_samples_leaf=5,
            n_jobs=-1,
            class_weight="balanced_subsample",
            random_state=seed,
        )
    if model_name == "hist_gradient_boosting":
        return HistGradientBoostingClassifier(
            max_iter=200,
            learning_rate=0.05,
            max_leaf_nodes=31,
            l2_regularization=0.01,
            random_state=seed,
        )
    raise ValueError(f"unknown supervised model: {model_name}")


def split_file(split_dir: Path, name: str) -> Path:
    gz = split_dir / f"{name}.csv.gz"
    if gz.exists():
        return gz
    return split_dir / f"{name}.csv"


def run_one(dataset_id: str, strategy: str, seed: int, models: list[str]) -> list[dict[str, object]]:
    split_dir = SPLIT_ROOT / dataset_id / strategy / f"seed_{seed}"
    manifest_path = split_dir / "split_manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"missing split manifest: {manifest_path}")

    left_col, right_col = edge_columns(dataset_id)
    train_pos = read_edges(split_file(split_dir, "train_pos"), left_col, right_col)
    train_neg = read_edges(split_file(split_dir, "train_neg"), left_col, right_col)
    adjacency = build_adjacency(train_pos)
    x_train, y_train, _ = build_feature_matrix(train_pos, train_neg, adjacency)

    eval_data = {}
    for split in ["val", "test"]:
        pos = read_edges(split_file(split_dir, f"{split}_pos"), left_col, right_col)
        neg = read_edges(split_file(split_dir, f"{split}_neg"), left_col, right_col)
        eval_data[split] = build_feature_matrix(pos, neg, adjacency)

    rows: list[dict[str, object]] = []
    for split, (_, y_eval, heuristic_scores) in eval_data.items():
        for heuristic, scores in heuristic_scores.items():
            rows.append(
                {
                    "dataset": dataset_id,
                    "negative_strategy": strategy,
                    "seed": seed,
                    "split": split,
                    "model": heuristic,
                    "model_family": "heuristic",
                    "auroc": float(roc_auc_score(y_eval, scores)),
                    "auprc": float(average_precision_score(y_eval, scores)),
                    "brier": "",
                    "nll": "",
                    "ece_10": "",
                    "train_seconds": 0.0,
                    "inference_seconds": 0.0,
                    "num_train": int(y_train.shape[0]),
                    "num_eval": int(y_eval.shape[0]),
                }
            )

    for model_name in models:
        model = make_model(model_name, seed)
        start = time.perf_counter()
        model.fit(x_train, y_train)
        train_seconds = time.perf_counter() - start
        for split, (x_eval, y_eval, _) in eval_data.items():
            start = time.perf_counter()
            y_prob = model.predict_proba(x_eval)[:, 1]
            inference_seconds = time.perf_counter() - start
            rows.append(
                {
                    "dataset": dataset_id,
                    "negative_strategy": strategy,
                    "seed": seed,
                    "split": split,
                    "model": model_name,
                    "model_family": "supervised_pair_features",
                    "auroc": float(roc_auc_score(y_eval, y_prob)),
                    "auprc": float(average_precision_score(y_eval, y_prob)),
                    "brier": float(brier_score_loss(y_eval, y_prob)),
                    "nll": float(log_loss(y_eval, y_prob, labels=[0, 1])),
                    "ece_10": expected_calibration_error(y_eval, y_prob, n_bins=10),
                    "train_seconds": train_seconds,
                    "inference_seconds": inference_seconds,
                    "num_train": int(y_train.shape[0]),
                    "num_eval": int(y_eval.shape[0]),
                }
            )
    return rows


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--datasets", nargs="+", default=DATASETS, choices=DATASETS)
    parser.add_argument("--strategies", nargs="+", default=STRATEGIES, choices=STRATEGIES)
    parser.add_argument("--seeds", nargs="+", type=int, default=list(range(42, 52)))
    parser.add_argument(
        "--models",
        nargs="+",
        default=["logistic_regression", "random_forest", "hist_gradient_boosting"],
        choices=["logistic_regression", "random_forest", "hist_gradient_boosting"],
    )
    parser.add_argument("--resume", action="store_true", help="Skip dataset/strategy/seed/model contexts already in the CSV.")
    return parser.parse_args()


def output_csv_path() -> Path:
    return RESULTS_DIR / "ppi_link_prediction_baselines.csv"


def append_rows(rows: list[dict[str, object]]) -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = output_csv_path()
    fields = list(rows[0])
    write_header = not csv_path.exists()
    with csv_path.open("a", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        if write_header:
            writer.writeheader()
        writer.writerows(rows)


def read_existing_contexts() -> set[tuple[str, str, int, str]]:
    csv_path = output_csv_path()
    if not csv_path.exists():
        return set()
    contexts: set[tuple[str, str, int, str]] = set()
    with csv_path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            contexts.add((row["dataset"], row["negative_strategy"], int(row["seed"]), row["model"]))
    return contexts


def write_reports_from_csv() -> None:
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = output_csv_path()
    if not csv_path.exists():
        return
    with csv_path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    (REPORTS_DIR / "phase1_ppi_link_prediction_baselines.json").write_text(
        json.dumps(rows, indent=2) + "\n",
        encoding="utf-8",
    )
    lines = [
        "# Phase 1 PPI Link Prediction Baselines",
        "",
        "| Dataset | Negatives | Seed | Split | Model | AUROC | AUPRC | ECE-10 | Train s |",
        "|---|---|---:|---|---|---:|---:|---:|---:|",
    ]
    for row in rows:
        ece = "" if row["ece_10"] == "" else f"{float(row['ece_10']):.6f}"
        lines.append(
            f"| `{row['dataset']}` | `{row['negative_strategy']}` | {row['seed']} | `{row['split']}` | "
            f"`{row['model']}` | {float(row['auroc']):.6f} | {float(row['auprc']):.6f} | {ece} | "
            f"{float(row['train_seconds']):.2f} |"
        )
    (REPORTS_DIR / "phase1_ppi_link_prediction_baselines.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    existing = read_existing_contexts() if args.resume else set()
    written = 0
    for dataset_id in args.datasets:
        for strategy in args.strategies:
            for seed in args.seeds:
                requested_contexts = {
                    (dataset_id, strategy, seed, model)
                    for model in [*HEURISTICS, *args.models]
                }
                if requested_contexts and requested_contexts.issubset(existing):
                    print(f"Skipping existing {dataset_id} / {strategy} / seed={seed}")
                    continue
                print(f"Running {dataset_id} / {strategy} / seed={seed}")
                rows = run_one(dataset_id, strategy, seed, args.models)
                if args.resume:
                    rows = [
                        row
                        for row in rows
                        if (
                            str(row["dataset"]),
                            str(row["negative_strategy"]),
                            int(row["seed"]),
                            str(row["model"]),
                        )
                        not in existing
                    ]
                    for row in rows:
                        existing.add((str(row["dataset"]), str(row["negative_strategy"]), int(row["seed"]), str(row["model"])))
                if not rows:
                    print("No new rows to append after resume filtering.")
                    continue
                append_rows(rows)
                written += len(rows)
                print(f"Appended {len(rows)} rows.")
    write_reports_from_csv()
    print(f"Appended {written} new rows to {output_csv_path()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
